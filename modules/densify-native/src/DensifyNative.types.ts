export type AdbState = 'disconnected' | 'connecting' | 'connected' | 'error';
export type AdbEvent = { state: AdbState; message?: string | null };
export type EngineEvent = { running: boolean; appliedSw?: number | null; activePkg?: string | null; errTitle?: string | null; errHint?: string | null };
export type InstalledApp = { pkg: string; name: string; isGame: boolean };
export type Capabilities = { hz: number; perf: boolean; guard: boolean; tile: boolean };
export type SettingsKind = 'usage' | 'developer' | 'overlay' | 'battery' | 'notifications' | 'settings';
export type NativeEvents = { onAdb: (e: AdbEvent) => void; onEngine: (e: EngineEvent) => void };
export interface NativeApi {
  storageGet(key: string): string | null;
  storageSet(key: string, value: string): boolean;
  setFlags(monitoring: boolean, restoreOnBoot: boolean): boolean;
  hasUsageAccess(): boolean;
  hasNotifications(): boolean;
  isBatteryUnrestricted(): boolean;
  hasSecureSettings(): boolean;
  hasOverlay(): boolean;
  nativeLibDir(): string;
  adbConnected(): boolean;
  isMonitoring(): boolean;
  battery(): { level: number; charging: boolean; tempC: number };
  openSettings(kind: SettingsKind): boolean;
  launchApp(pkg: string): boolean;
  requestAddTile(): boolean;
  getInstalledApps(): Promise<InstalledApp[]>;
  getAppIcon(pkg: string): Promise<string>;
  startPairing(): boolean;
  connect(): Promise<boolean>;
  grantSelf(): Promise<boolean>;
  capabilities(): Promise<Capabilities>;
  readDensity(): Promise<{ physical: number; effective: number }>;
  readSw(): Promise<{ sw: number; physSw: number; dpi: number; physDpi: number; shortSide: number }>;
  setSw(sw: number): Promise<number>;
  setDensity(dpi: number): Promise<number>;
  restoreDefault(): Promise<number>;
  readSize(): Promise<{ physW: number; physH: number; override: string | null }>;
  setSize(w: number, h: number): Promise<boolean>;
  resetSize(): Promise<boolean>;
  getStretch(): { w: number; h: number; on: boolean };
  saveStretch(w: number, h: number): boolean;
  applyStretch(w: number, h: number): Promise<boolean>;
  resetStretch(): Promise<boolean>;
  sdkInt(): number;
  shell(cmd: string): Promise<string>;
  logs(): string[];
  clearLogs(): boolean;
  previewFloating(seconds: number): boolean;
  sessionExec(cmd: string): Promise<string>;
  sessionReset(): boolean;
  listPackages(): Promise<{ packageName: string; versionName: string; versionCode: number; appLabel: string; isSystem: boolean; uid: number }[]>;
  disconnect(): Promise<boolean>;
  isPaired(): boolean;
  bridgeActive(): boolean;
  enableBridge(): Promise<boolean>;
  disableBridge(): Promise<boolean>;
  startMonitoring(): boolean;
  stopMonitoring(): boolean;
  deviceInfo(): Promise<string>;
  shizukuStatus(): Promise<string>;
  shizukuRequest(): Promise<string>;
  shizukuOpen(): boolean;
  pairManual(port: number, code: string): Promise<boolean>;
  perfWatch(on: boolean): boolean;
  perfLive(): string;
  perfSessions(): string;
  perfClear(): boolean;
  optimizeNow(): Promise<string>;
  compileApp(pkg: string): Promise<string>;
  recStatus(): string;
  recCaps(): string;
  recPlan(w: number, h: number): string;
  recStart(): boolean;
  recPause(): boolean;
  recResume(): boolean;
  recStop(): boolean;
  recOpenLast(): boolean;
}
